// pppd renders the options of one PPPoE session. The Talos kernel has PPP but not kernel PPPoE,
// so the discovery and the PPPoE framing run in user space (rp-pppoe's pppoe, through pppd's pty).
func pppd(p config.PPPoE, e env.Env) string {
	var b strings.Builder

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	pty := "/usr/sbin/pppoe -I " + e.Resolve(p.Link) + " -T 80"
	if p.ServiceName != "" {
		pty += " -S " + p.ServiceName
	}

	line("# Generated by routald from router.yaml; do not edit. Contains the PPPoE password.")
	line("pty %q", pty)
	line("ifname %s", p.Interface)
	line("user %q", p.Username)
	line("password %q", p.Password)
	line("noauth")      // the ISP authenticates us, not the other way round
	line("noipdefault") // our address comes from the ISP
	line("persist")     // redial forever
	line("maxfail 0")
	line("holdoff 5")
	line("mtu %d", p.MTU)
	line("mru %d", p.MTU)
	line("lcp-echo-interval 20")
	line("lcp-echo-failure 3")
	line("noaccomp")
	line("default-asyncmap")
	line("nodeflate")
	line("nobsdcomp")
	line("novj")
	line("nodetach")
	line("logfd 2")

	if *p.DefaultRoute {
		line("defaultroute")
		line("replacedefaultroute")
	}

	if *p.IPv6 {
		line("+ipv6") // link-local over IPCP6; the prefix comes from PrefixDelegationConfig
	} else {
		line("noipv6")
	}

	return b.String()
}

// inadyn renders the dynamic DNS client, one provider section per DynamicDNSConfig.
func inadyn(cfg *config.Config) string {
	var b strings.Builder

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	period := time.Duration(1<<63 - 1)
	ipv6 := false

	for _, d := range cfg.DynamicDNS {
		period = min(period, d.Period)
		ipv6 = ipv6 || d.IPv6
	}

	line("# Generated by routald from router.yaml; do not edit. Contains provider credentials.")
	line("period = %d", int(period/time.Second))
	line("allow-ipv6 = %v", ipv6)

	for i, d := range cfg.DynamicDNS {
		if d.Provider == "custom" {
			line("custom routal-%s:%d {", d.Name, i+1)
			line("\tddns-server = %q", d.Server)
			line("\tddns-path = %q", d.Path)
		} else {
			line("provider %s:%d {", d.Provider, i+1)
		}

		if d.Username != "" {
			line("\tusername = %q", d.Username)
		}

		if d.Password != "" {
			line("\tpassword = %q", d.Password)
		}

		hosts := make([]string, 0, len(d.Hostnames))
		for _, h := range d.Hostnames {
			hosts = append(hosts, fmt.Sprintf("%q", h))
		}

		line("\thostname = { %s }", strings.Join(hosts, ", "))
		line("\tssl = %v", *d.SSL)

		if d.Link != "" {
			// the address on the WAN link rather than what a web service sees
			cmd := "/usr/local/bin/routald addr " + d.Link
			if d.IPv6 {
				cmd = "/usr/local/bin/routald addr -6 " + d.Link
			}

			line("\tcheckip-command = %q", cmd)
		}

		line("}")
	}

	return b.String()
}
