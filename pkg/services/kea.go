// Kea lease files (memfile, CSV) in Dirs.State.
const (
	Kea4LeaseFile = "kea-leases4.csv"
	Kea6LeaseFile = "kea-leases6.csv"
)

type obj = map[string]any

// linkAddr finds the router's address on a link inside subnet (or of a family when subnet is
// invalid). Offline, it returns a placeholder: the first host of subnet.
func linkAddr(e env.Env, link string, subnet netip.Prefix, v4 bool) (netip.Addr, bool) {
	if a, ok := e.Addr(link, subnet, v4); ok {
		return a, true
	}

	if e.Offline && subnet.IsValid() {
		return subnet.Masked().Addr().Next(), true
	}

	return netip.Addr{}, false
}

func listensOn(links []string, link string) bool {
	for _, l := range links {
		if l == link {
			return true
		}
	}

	return false
}

func dnsLinks(cfg *config.Config) []string {
	if cfg.DNSServer == nil {
		return nil
	}

	return cfg.DNSServer.ListenLinks
}

func ntpLinks(cfg *config.Config) []string {
	if cfg.NTPServer == nil {
		return nil
	}

	return cfg.NTPServer.ListenLinks
}

func keaLoggers(name string) []obj {
	return []obj{{
		"name":           name,
		"severity":       "INFO",
		"output-options": []obj{{"output": "stdout", "pattern": "%-5p %m\n"}},
	}}
}

func keaInterfaces(ifaces []string) obj {
	return obj{
		"interfaces": ifaces,
		// links may appear later (VLANs): keep serving the others, retry the missing ones
		"service-sockets-require-all":     false,
		"service-sockets-max-retries":     1000000,
		"service-sockets-retry-wait-time": 5000,
	}
}

func marshal(header string, v any) string {
	out, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		panic(err) // only maps, slices and strings
	}

	return header + string(out) + "\n"
}

// kea4 renders kea-dhcp4. A DHCPServerConfig without subnet takes it from the router's address on
// the link that contains rangeStart; until that address exists, the pool is left out.
func kea4(cfg *config.Config, e env.Env, d Dirs) (string, []string) {
	var warn []string

	ifaces, subnets := []string{}, []obj{}

	for i, srv := range cfg.DHCPServers {
		subnet := srv.Subnet

		var router netip.Addr

		if !subnet.IsValid() {
			for _, p := range e.Addrs(srv.Link) {
				if p.Masked().Contains(srv.RangeStart) {
					subnet, router = p.Masked(), p.Addr()

					break
				}
			}
		}

		if !subnet.IsValid() && e.Offline {
			subnet = netip.PrefixFrom(srv.RangeStart, 24).Masked() // placeholder for config checks
		}

		if !subnet.IsValid() {
			warn = append(warn, fmt.Sprintf("DHCP %q: no address on link %s contains %s yet", srv.Name, srv.Link, srv.RangeStart))

			continue
		}

		if !router.IsValid() {
			router, _ = linkAddr(e, srv.Link, subnet, true)
		}

		options := []obj{}

		opt := func(name, data string) { options = append(options, obj{"name": name, "data": data}) }

		switch {
		case srv.Gateway.IsValid():
			opt("routers", srv.Gateway.String())
		case router.IsValid():
			opt("routers", router.String())
		}

		switch {
		case len(srv.DNSServers) > 0:
			opt("domain-name-servers", joinAddrs(srv.DNSServers, ", "))
		case listensOn(dnsLinks(cfg), srv.Link) && router.IsValid():
			opt("domain-name-servers", router.String())
		}

		domain := srv.Domain
		if domain == "" && cfg.DNSServer != nil {
			domain = cfg.DNSServer.LocalDomain
		}

		if domain != "" {
			opt("domain-name", domain)
		}

		if listensOn(ntpLinks(cfg), srv.Link) && router.IsValid() {
			opt("ntp-servers", router.String())
		}

		reservations := []obj{}

		for _, l := range srv.StaticLeases {
			r := obj{"hw-address": strings.ToLower(l.MAC), "ip-address": l.Address.String()}
			if l.Hostname != "" {
				r["hostname"] = l.Hostname
			}

			reservations = append(reservations, r)
		}

		iface := e.Resolve(srv.Link)
		ifaces = append(ifaces, iface)

		subnets = append(subnets, obj{
			"id":             i + 1,
			"subnet":         subnet.String(),
			"interface":      iface,
			"pools":          []obj{{"pool": fmt.Sprintf("%s - %s", srv.RangeStart, srv.RangeEnd)}},
			"valid-lifetime": int(srv.LeaseTime / time.Second),
			"option-data":    options,
			"reservations":   reservations,
			"user-context":   obj{"routal": srv.Name},
		})
	}

	return marshal("// Generated by routald from router.yaml; do not edit.\n", obj{"Dhcp4": obj{
		"interfaces-config": keaInterfaces(ifaces),
		"lease-database": obj{
			"type": "memfile", "persist": true, "name": d.State + "/" + Kea4LeaseFile, "lfc-interval": 3600,
		},
		"authoritative": true,
		// keep the hostname clients send in the lease: routald publishes it in DNS
		"ddns-send-updates":         false,
		"ddns-replace-client-name":  "never",
		"hostname-char-set":         "[^A-Za-z0-9.-]",
		"hostname-char-replacement": "",
		"subnet4":                   subnets,
		"loggers":                   keaLoggers("kea-dhcp4"),
	}}), warn
}

func needsDHCPv6(cfg *config.Config) bool {
	for _, ra := range cfg.RouterAdvertisements {
		if ra.Other {
			return true
		}
	}

	return false
}

// kea6 renders kea-dhcp6 for stateless DHCPv6 (RA "other" flag): options only, no addresses.
func kea6(cfg *config.Config, e env.Env, d Dirs) (string, []string) {
	var warn []string

	ifaces, subnets := []string{}, []obj{}

	for i, ra := range cfg.RouterAdvertisements {
		if !ra.Other {
			continue
		}

		prefix := ra.Prefixes[0]

		options := []obj{}

		switch {
		case len(ra.DNSServers) > 0:
			options = append(options, obj{"name": "dns-servers", "data": joinAddrs(ra.DNSServers, ", ")})
		case listensOn(dnsLinks(cfg), ra.Link):
			if a, ok := linkAddr(e, ra.Link, prefix, false); ok {
				options = append(options, obj{"name": "dns-servers", "data": a.String()})
			} else {
				warn = append(warn, fmt.Sprintf("DHCPv6 %q: no address in %s on %s yet for the DNS option", ra.Name, prefix, ra.Link))
			}
		}

		if cfg.DNSServer != nil && cfg.DNSServer.LocalDomain != "" {
			options = append(options, obj{"name": "domain-search", "data": cfg.DNSServer.LocalDomain})
		}

		iface := e.Resolve(ra.Link)
		ifaces = append(ifaces, iface)

		subnets = append(subnets, obj{
			"id":           i + 1,
			"subnet":       prefix.String(),
			"interface":    iface,
			"option-data":  options,
			"user-context": obj{"routal": ra.Name},
		})
	}

	return marshal("// Generated by routald from router.yaml; do not edit.\n", obj{"Dhcp6": obj{
		"interfaces-config": keaInterfaces(ifaces),
		"lease-database":    obj{"type": "memfile", "persist": true, "name": d.State + "/" + Kea6LeaseFile, "lfc-interval": 3600},
		"subnet6":           subnets,
		"loggers":           keaLoggers("kea-dhcp6"),
	}}), warn
}

func joinAddrs(addrs []netip.Addr, sep string) string {
	s := make([]string, 0, len(addrs))
	for _, a := range addrs {
		s = append(s, a.String())
	}

	return strings.Join(s, sep)
}
