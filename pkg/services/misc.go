// radvd renders router advertisements. Without explicit prefixes, radvd announces every /64 on the
// link ("prefix ::/64"), which follows addresses Talos assigns (e.g. from a delegated prefix).
func radvd(cfg *config.Config, e env.Env) (string, []string) {
	var (
		b    strings.Builder
		warn []string
	)

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	line("# Generated by routald from router.yaml; do not edit.")

	for _, ra := range cfg.RouterAdvertisements {
		onoff := map[bool]string{true: "on", false: "off"}
		lifetime := min(int(ra.RouterLifetime/time.Second), 9000)

		line("interface %s {", e.Resolve(ra.Link))
		line("\tAdvSendAdvert on;")
		line("\tMinRtrAdvInterval 20;")
		line("\tMaxRtrAdvInterval 60;")
		line("\tAdvDefaultLifetime %d;", max(lifetime, 60))
		line("\tAdvManagedFlag %s;", onoff[ra.Managed])
		line("\tAdvOtherConfigFlag %s;", onoff[ra.Other])

		prefixes := ra.Prefixes
		if len(prefixes) == 0 {
			prefixes = []netip.Prefix{netip.MustParsePrefix("::/64")}
		}

		for _, p := range prefixes {
			line("\tprefix %s {", p)
			line("\t\tAdvOnLink on;")
			line("\t\tAdvAutonomous on;")
			line("\t};")
		}

		dns := ra.DNSServers

		if len(dns) == 0 && listensOn(dnsLinks(cfg), ra.Link) {
			var within netip.Prefix
			if len(ra.Prefixes) > 0 {
				within = ra.Prefixes[0]
			}

			if a, ok := linkAddr(e, ra.Link, within, false); ok {
				dns = []netip.Addr{a}
			} else {
				warn = append(warn, fmt.Sprintf("RA %q: no IPv6 address on %s yet to announce as DNS server", ra.Name, ra.Link))
			}
		}

		if len(dns) > 0 {
			line("\tRDNSS %s {", joinAddrs(dns, " "))
			line("\t};")

			if cfg.DNSServer != nil && cfg.DNSServer.LocalDomain != "" {
				line("\tDNSSL %s {", cfg.DNSServer.LocalDomain)
				line("\t};")
			}
		}

		line("};")
	}

	return b.String(), warn
}

// chrony renders an NTP server for the subnets of the listen links.
func chrony(cfg *config.Config, e env.Env, d Dirs) (string, []string) {
	var (
		b    strings.Builder
		warn []string
	)

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	line("# Generated by routald from router.yaml; do not edit.")

	for _, u := range cfg.NTPServer.Upstreams {
		line("server %s iburst", u)
	}

	var allow []string

	for _, l := range cfg.NTPServer.ListenLinks {
		found := false

		for _, p := range e.Addrs(l) {
			if !p.Addr().IsLinkLocalUnicast() {
				allow = append(allow, p.Masked().String())
				found = true
			}
		}

		if !found && !e.Offline {
			warn = append(warn, fmt.Sprintf("NTP: link %s has no address yet", l))
		}
	}

	slices.Sort(allow)

	for _, a := range slices.Compact(allow) {
		line("allow %s", a)
	}

	line("local stratum 10") // keep serving if the upstreams are unreachable
	line("driftfile %s/chrony.drift", d.State)
	line("pidfile %s/chronyd.pid", d.Run)
	line("cmdport 0")

	return b.String(), warn
}

// avahi renders an mDNS reflector that publishes nothing itself.
func avahi(cfg *config.Config, e env.Env) string {
	var ifaces []string
	for _, l := range cfg.MDNSReflector.Links {
		ifaces = append(ifaces, e.Resolve(l))
	}

	return fmt.Sprintf(`# Generated by routald from router.yaml; do not edit.
[server]
use-ipv4=yes
use-ipv6=yes
allow-interfaces=%s
enable-dbus=no
ratelimit-interval-usec=1000000
ratelimit-burst=1000

[wide-area]
enable-wide-area=no

[publish]
disable-publishing=yes
disable-user-service-publishing=yes

[reflector]
enable-reflector=yes
`, strings.Join(ifaces, ","))
}

// miniupnpd renders UPnP IGD + NAT-PMP/PCP, writing its mappings in the routal_upnp table.
func miniupnpd(cfg *config.Config, e env.Env, d Dirs) (string, []string) {
	u := cfg.UPnP

	var (
		b    strings.Builder
		warn []string
	)

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	ext := e.Resolve(u.ExternalLink)
	sum := sha256.Sum256([]byte("routal-upnp-" + ext))

	line("# Generated by routald from router.yaml; do not edit.")
	line("ext_ifname=%s", ext)

	for _, l := range u.InternalLinks {
		line("listening_ip=%s", e.Resolve(l))
	}

	line("http_port=5000")
	line("enable_upnp=yes")
	line("enable_natpmp=yes")
	line("enable_pcp_pmp=yes")
	line("secure_mode=yes") // a device may only map ports to itself
	line("system_uptime=yes")
	line("ext_allow_private_ipv4=yes") // behind a CGNAT or another router, mappings still help
	line("lease_file=%s/upnp.leases", d.State)
	line("uuid=%x-%x-%x-%x-%x", sum[0:4], sum[4:6], sum[6:8], sum[8:10], sum[10:16])
	line("upnp_table_name=%s", nft.UPnPTable)
	line("upnp_nat_table_name=%s", nft.UPnPTable)
	line("upnp_forward_chain=forward")
	line("upnp_nat_chain=prerouting")
	line("upnp_nat_postrouting_chain=postrouting")
	line("upnp_nftables_family_split=no")

	subnets := u.InternalSubnets
	if len(subnets) == 0 {
		for _, l := range u.InternalLinks {
			for _, p := range e.Addrs(l) {
				if p.Addr().Is4() && !p.Addr().IsLinkLocalUnicast() {
					subnets = append(subnets, p.Masked())
				}
			}
		}
	}

	if len(subnets) == 0 {
		if !e.Offline {
			warn = append(warn, "UPnP: no IPv4 address on the internal links yet")
		}

		subnets = []netip.Prefix{netip.MustParsePrefix("0.0.0.0/0")}
	}

	for _, p := range u.ExternalPorts {
		for _, s := range subnets {
			if s.Addr().Is4() {
				line("allow %s %s 1-65535", p, s)
			}
		}
	}

	line("deny 0-65535 0.0.0.0/0 0-65535")

	return b.String(), warn
}
