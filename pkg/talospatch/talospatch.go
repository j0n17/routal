// Package talospatch turns a router config into a Talos machine config patch.
//
// The patch carries router.yaml to the routald extension (ExtensionServiceConfig) and opens the
// router ports used by `to: self` rules and port forwards in the Talos ingress firewall
// (NetworkRuleConfig).
package talospatch

import (
	"bytes"
	"fmt"
	"net/netip"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/j0n17/routal/pkg/config"
)

// ServiceName is the extension service name (manifest and ExtensionServiceConfig).
const ServiceName = "routald"

// ConfigPath is where routald reads its config inside the extension container.
const ConfigPath = "/etc/routal/router.yaml"

type extensionServiceConfig struct {
	APIVersion  string       `yaml:"apiVersion"`
	Kind        string       `yaml:"kind"`
	Name        string       `yaml:"name"`
	ConfigFiles []configFile `yaml:"configFiles"`
}

type configFile struct {
	Content   literal `yaml:"content"`
	MountPath string  `yaml:"mountPath"`
}

type literal string

func (l literal) MarshalYAML() (any, error) {
	return &yaml.Node{Kind: yaml.ScalarNode, Style: yaml.LiteralStyle, Value: string(l)}, nil
}

type networkRuleConfig struct {
	APIVersion   string        `yaml:"apiVersion"`
	Kind         string        `yaml:"kind"`
	Name         string        `yaml:"name"`
	PortSelector portSelector  `yaml:"portSelector"`
	Ingress      []ingressRule `yaml:"ingress"`
}

type portSelector struct {
	Ports    []any  `yaml:"ports"`
	Protocol string `yaml:"protocol"`
}

type ingressRule struct {
	Subnet string `yaml:"subnet"`
}

// Generate returns the Talos patch for a router config file (raw is embedded verbatim).
func Generate(raw []byte, cfg *config.Config) ([]byte, error) {
	docs := []any{
		extensionServiceConfig{
			APIVersion: "v1alpha1",
			Kind:       "ExtensionServiceConfig",
			Name:       ServiceName,
			ConfigFiles: []configFile{{
				Content:   literal(strings.TrimRight(string(raw), "\n") + "\n"),
				MountPath: ConfigPath,
			}},
		},
	}

	for _, r := range cfg.Rules {
		if r.To != config.SelfZone || r.Action != config.ActionAccept {
			continue
		}

		// the zone's links are enforced by routald's input chain
		docs = append(docs, ruleFor("routal-"+r.Name, r.Protocol, r.Ports, r.SourceSubnets))
	}

	// Talos filters traffic to the router's own addresses in a prerouting chain that runs before
	// routald's DNAT, so forwarded ports must be opened there too.
	for _, pf := range cfg.PortForwards {
		docs = append(docs, ruleFor("routal-pf-"+pf.Name, pf.Protocol, pf.Ports, pf.SourceSubnets))
	}

	var buf bytes.Buffer

	buf.WriteString("# Generated by `routald talos-patch`; apply with `talosctl patch mc --patch @<this file>`.\n")

	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)

	for _, d := range docs {
		if err := enc.Encode(d); err != nil {
			return nil, fmt.Errorf("encoding patch: %w", err)
		}
	}

	if err := enc.Close(); err != nil {
		return nil, err
	}

	return buf.Bytes(), nil
}

func ruleFor(name string, proto config.Protocol, ports []config.PortRange, subnets []netip.Prefix) networkRuleConfig {
	nrc := networkRuleConfig{
		APIVersion:   "v1alpha1",
		Kind:         "NetworkRuleConfig",
		Name:         name,
		PortSelector: portSelector{Protocol: string(proto)},
	}

	for _, p := range ports {
		if p.Lo == p.Hi {
			nrc.PortSelector.Ports = append(nrc.PortSelector.Ports, int(p.Lo))
		} else {
			nrc.PortSelector.Ports = append(nrc.PortSelector.Ports, p.String())
		}
	}

	for _, s := range subnets {
		nrc.Ingress = append(nrc.Ingress, ingressRule{Subnet: s.String()})
	}

	if len(nrc.Ingress) == 0 {
		nrc.Ingress = []ingressRule{{Subnet: "0.0.0.0/0"}, {Subnet: "::/0"}}
	}

	return nrc
}
