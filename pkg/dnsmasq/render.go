// Package dnsmasq renders the DHCP, DNS and router advertisement documents as a dnsmasq config.
package dnsmasq

import (
	"fmt"
	"net/netip"
	"slices"
	"strings"
	"time"

	"github.com/j0n17/routal/pkg/config"
)

// HostDNS is the Talos host DNS resolver, used when DNSServerConfig has no upstreams.
const HostDNS = "127.0.0.53"

// Needed reports whether the config uses any dnsmasq feature.
func Needed(cfg *config.Config) bool {
	return cfg.DNSServer != nil || len(cfg.DHCPServers) > 0 || len(cfg.RouterAdvertisements) > 0
}

// Render returns the dnsmasq config. resolve maps configured link names to kernel names.
func Render(cfg *config.Config, resolve func(string) string, leaseFile string) string {
	if resolve == nil {
		resolve = func(n string) string { return n }
	}

	var b strings.Builder

	line := func(format string, args ...any) { fmt.Fprintf(&b, format+"\n", args...) }

	line("# Generated by routald from router.yaml; do not edit.")
	line("user=root")
	line("bind-dynamic")
	line("no-hosts")
	line("log-facility=-")
	line("log-dhcp")

	var links []string

	if cfg.DNSServer != nil {
		links = append(links, cfg.DNSServer.ListenLinks...)
	}

	for _, d := range cfg.DHCPServers {
		links = append(links, d.Link)
	}

	for _, ra := range cfg.RouterAdvertisements {
		links = append(links, ra.Link)
	}

	for _, l := range uniqueResolved(links, resolve) {
		line("interface=%s", l)
	}

	renderDNS(cfg, line)
	renderDHCP(cfg, leaseFile, line)
	renderRA(cfg, resolve, line)

	return b.String()
}

func renderDNS(cfg *config.Config, line func(string, ...any)) {
	d := cfg.DNSServer
	if d == nil {
		line("port=0 # no DNSServerConfig: DNS disabled")

		return
	}

	line("cache-size=%d", d.CacheSize)
	line("domain-needed")
	line("bogus-priv")
	line("no-resolv")

	if len(d.Upstreams) == 0 {
		line("server=%s", HostDNS)
	}

	for _, u := range d.Upstreams {
		line("server=%s", u)
	}

	if d.LocalDomain != "" {
		line("domain=%s", d.LocalDomain)
		line("local=/%s/", d.LocalDomain)
		line("expand-hosts")
	}

	for _, r := range d.LocalRecords {
		line("host-record=%s,%s", r.Name, joinAddrs(r.Addresses))
	}

	if !*d.RegisterDHCPLeases {
		line("dhcp-ignore-names")
	}
}

func renderDHCP(cfg *config.Config, leaseFile string, line func(string, ...any)) {
	if len(cfg.DHCPServers) == 0 {
		return
	}

	line("dhcp-authoritative")
	line("dhcp-leasefile=%s", leaseFile)

	for _, d := range cfg.DHCPServers {
		tag := "dhcp-" + d.Name

		// the subnet (and so the interface) is derived from the router's address on that link
		line("dhcp-range=set:%s,%s,%s,%ds", tag, d.RangeStart, d.RangeEnd, int(d.LeaseTime/time.Second))

		if d.Gateway.IsValid() {
			line("dhcp-option=tag:%s,option:router,%s", tag, d.Gateway)
		}

		switch {
		case len(d.DNSServers) > 0:
			line("dhcp-option=tag:%s,option:dns-server,%s", tag, joinAddrs(d.DNSServers))
		case cfg.DNSServer == nil:
			line("dhcp-option=tag:%s,option:dns-server # no DNS server on the router: send none", tag)
		}

		if d.Domain != "" {
			line("dhcp-option=tag:%s,option:domain-name,%s", tag, d.Domain)
		}

		for _, l := range d.StaticLeases {
			host := fmt.Sprintf("dhcp-host=%s,%s", strings.ToLower(l.MAC), l.Address)
			if l.Hostname != "" {
				host += "," + l.Hostname
			}

			line("%s", host)
		}
	}
}

func renderRA(cfg *config.Config, resolve func(string) string, line func(string, ...any)) {
	if len(cfg.RouterAdvertisements) == 0 {
		return
	}

	line("enable-ra")

	for _, ra := range cfg.RouterAdvertisements {
		tag := "ra-" + ra.Name
		link := resolve(ra.Link)

		mode := "ra-only" // SLAAC, no DHCPv6
		if ra.Other {
			mode = "ra-stateless" // SLAAC + DHCPv6 for options (DNS)
		}

		if len(ra.Prefixes) == 0 {
			line("dhcp-range=set:%s,::,constructor:%s,%s", tag, link, mode)
		}

		// an explicit prefix selects the interface that has an address in it
		for _, p := range ra.Prefixes {
			line("dhcp-range=set:%s,%s,%s,%d", tag, p.Addr(), mode, p.Bits())
		}

		line("ra-param=%s,60,%d", link, int(ra.RouterLifetime/time.Second))

		if len(ra.DNSServers) > 0 {
			var addrs []string
			for _, a := range ra.DNSServers {
				addrs = append(addrs, "["+a.String()+"]")
			}

			line("dhcp-option=tag:%s,option6:dns-server,%s", tag, strings.Join(addrs, ","))
		}
	}
}

func uniqueResolved(links []string, resolve func(string) string) []string {
	out := make([]string, 0, len(links))
	for _, l := range links {
		out = append(out, resolve(l))
	}

	slices.Sort(out)

	return slices.Compact(out)
}

func joinAddrs(addrs []netip.Addr) string {
	s := make([]string, 0, len(addrs))
	for _, a := range addrs {
		s = append(s, a.String())
	}

	return strings.Join(s, ",")
}
